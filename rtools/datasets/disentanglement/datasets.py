import torch
import urllib.request
import logging
import numpy as np
from copy import deepcopy
from torch.utils.data import Dataset
from pathlib import Path

class DSprites(Dataset):
    """
    DSprites dataset for disentanglement testing.

    A large dataset of 64x64 gray-scale images of 2D sprites with controlled disentangled
    factors of variation. This dataset is useful for evaluating disentangled
    representation learning algorithms.

    The dataset contains rendered 2D sprites parameterized by:
    - Color (1 factor)
    - Shape (3 factors: square, ellipse, heart)
    - Scale (6 factors)
    - Orientation (40 factors)
    - X position (32 factors)
    - Y position (32 factors)

    For citations:
        @misc{dsprites17,
            author = {Loic Matthey and Irina Higgins and Demis Hassabis and Alexander Lerchner},
            title = {dSprites: Disentanglement testing Sprites dataset},
            howpublished= {https://github.com/deepmind/dsprites-dataset/},
            year = "2017",
        }

    Parameters
    ----------
    K : int, optional
        Number of latent factors to vary when creating paired samples.
        If K=-1 (default), a random number of factors is chosen per sample.
        Must satisfy 0 < K < number_of_latent_factors-1.
    paired : bool, optional
        If True (default), returns paired samples (x1, x2) with (y1, y2) labels,
        where x2 is a variation of x1 by K latent factors.
        If False, returns single samples (x, y).

    Attributes
    ----------
    X : torch.Tensor
        Images tensor of shape (n_samples, 1, 64, 64).
    latents_classes : torch.Tensor
        Discrete latent class indices for each sample.
    latents_values : torch.Tensor
        Continuous latent values for each sample.
    latents_factors : int
        Number of latent factors.
    latents_sizes : torch.Tensor
        Size of each latent factor dimension.
    latents_bases : torch.Tensor
        Bases for converting latent indices to dataset indices.
    K : int
        Number of factors to vary in paired mode.

    Notes
    -----
    - The dataset is automatically downloaded on first use to a data directory.
    - Images are returned as float32 tensors with shape (1, 64, 64).
    - In paired mode, x2 is generated by varying K factors of x1.
    """
    _NPZ_URL = 'https://github.com/google-deepmind/dsprites-dataset/raw/refs/heads/master/dsprites_ndarray_co1sh3sc6or40x32y32_64x64.npz'
    def __init__(self, 
                 K: int = -1, 
                 paired: bool = True):
        """
        Initialize the DSprites dataset.

        Parameters
        ----------
        K : int, optional
            Number of latent factors to vary. Use -1 for random selection per sample.
        paired : bool, optional
            If True, return paired samples with K factors varying between them.
        """
        self.paired = paired
        self.DATA_PATH = Path('..') / 'data' / 'dsprites'
        self.DATA_PATH.mkdir(parents=True, exist_ok=True)
        
        dataset_path = self.DATA_PATH / 'dsprites.npz'
        if not dataset_path.exists():
            logging.info('Downloading dataset from %s', DSprites._NPZ_URL)
            urllib.request.urlretrieve(DSprites._NPZ_URL, str(dataset_path))
            logging.info('Dataset stored in %s', dataset_path)
        
        data = np.load(dataset_path, allow_pickle=True)

        # storing data as tensors
        self.X = torch.as_tensor(data['imgs'], dtype=torch.float32)
        self.latents_classes = torch.as_tensor(data['latents_classes'], dtype=torch.int64)
        self.latents_values = torch.as_tensor(data['latents_values'], dtype=torch.int64)
        
        # adding channel dim
        self.X = self.X.unsqueeze(1)

        self.latents_factors = self.latents_classes.shape[1]
        # from https://github.com/google-deepmind/dsprites-dataset/blob/master/dsprites_reloading_example.ipynb
        # together with latent_to_index fn
        latents_sizes = np.array([len(self.latents_classes[:, d].unique()) for d in range(self.latents_factors)])
        latents_bases = np.concatenate((latents_sizes[::-1].cumprod()[::-1][1:],
                                np.array([1,])))
        self.latents_sizes = torch.as_tensor(latents_sizes, dtype=torch.int64)
        self.latents_bases = torch.as_tensor(latents_bases, dtype=torch.int64)

        # latent common factors
        self.K = K
        if K != -1: # random
            assert 0 < self.K < self.latents_factors, 'k must be in 0 < k < #latentdims'

    
    def __len__(self) -> int:
        """Return the total number of samples in the dataset."""
        return self.X.shape[0]
    
    def latent_to_index(self, latents: torch.Tensor) -> torch.Tensor:
        """
        Convert latent factor indices to dataset sample index.

        Parameters
        ----------
        latents : torch.Tensor
            Latent factor indices.

        Returns
        -------
        torch.Tensor
            Dataset index corresponding to the latent factors.
        """
        return torch.dot(latents, self.latents_bases)
    
    def __getitem__(self, index):
        """
        Get a sample from the dataset.

        Parameters
        ----------
        index : int
            Index of the sample to retrieve.

        Returns
        -------
        If paired=False:
            tuple of (image, latent_factors)
                image : torch.Tensor
                    Image tensor of shape (1, 64, 64).
                latent_factors : torch.Tensor
                    Discrete latent factor indices.

        If paired=True:
            tuple of ((image1, image2), (factors1, factors2))
                image1, image2 : torch.Tensor
                    Paired images differing in K latent factors.
                factors1, factors2 : torch.Tensor
                    Discrete latent factor indices for each image.
        """
        x1, y1 = self.X[index], self.latents_classes[index]
        if not self.paired:
            return x1, y1
        
        k: int = self.K if self.K != -1 else int(torch.randint(1, int(self.latents_factors), ()))
        
        y2 = y1.clone()
        
        idxs_k = torch.randperm(self.latents_factors-1)[:k]+1
        S = self.latents_sizes[idxs_k]
        
        offsets = (torch.rand(k) * (S-1)).long() + 1
        y2[idxs_k] = (y2[idxs_k] + offsets) % S
        x2 = self.X[self.latent_to_index(y2)]

        return (x1, x2), (y1, y2)
        
class ThreeDShapes(Dataset):
    """
    3DShapes: Disentanglement Testing Dataset.
    from: https://github.com/google-deepmind/3d-shapes

    3dshapes is a dataset of 3D shapes procedurally generated from 6 ground truth independent latent factors. 
    These factors are floor colour, wall colour, object colour, scale, shape and orientation.

    The dataset contains rendered 2D sprites parameterized by:
    - floor hue: 10 values linearly spaced in [0, 1]
    - wall hue: 10 values linearly spaced in [0, 1]
    - object hue: 10 values linearly spaced in [0, 1]
    - scale: 8 values linearly spaced in [0, 1]
    - shape: 4 values in [0, 1, 2, 3]
    - orientation: 15 values linearly spaced in [-30, 30]


    For citations:
        @misc{3dshapes18,
            title={3D Shapes Dataset},
            author={Burgess, Chris and Kim, Hyunjik},
            howpublished={https://github.com/deepmind/3dshapes-dataset/},
            year={2018}
        }

    Parameters
    ----------
    K : int, optional
        Number of latent factors to vary when creating paired samples.
        If K=-1 (default), a random number of factors is chosen per sample.
        Must satisfy 0 < K < number_of_latent_factors-1.
    paired : bool, optional
        If True (default), returns paired samples (x1, x2) with (y1, y2) labels,
        where x2 is a variation of x1 by K latent factors.
        If False, returns single samples (x, y).

    Attributes
    ----------
    X : torch.Tensor
        Images tensor of shape (n_samples, 1, 64, 64).
    latents_classes : torch.Tensor
        Discrete latent class indices for each sample.
    latents_values : torch.Tensor
        Continuous latent values for each sample.
    latents_factors : int
        Number of latent factors.
    latents_sizes : torch.Tensor
        Size of each latent factor dimension.
    latents_bases : torch.Tensor
        Bases for converting latent indices to dataset indices.
    K : int
        Number of factors to vary in paired mode.

    Notes
    -----
    - The dataset is automatically downloaded on first use to a data directory.
    - Images are returned as float32 tensors with shape (1, 64, 64).
    - In paired mode, x2 is generated by varying K factors of x1.
    """
    _H5_URL = 'https://storage.googleapis.com/3d-shapes/3dshapes.h5'
    def __init__(self, 
                 K: int = -1, 
                 paired: bool = True):
        """
        Initialize the 3DShapes dataset.

        Parameters
        ----------
        K : int, optional
            Number of latent factors to vary. Use -1 for random selection per sample.
        paired : bool, optional
            If True, return paired samples with K factors varying between them.
        """
        self.paired = paired
        self.DATA_PATH = Path('..') / 'data' / '3dshapes'
        self.DATA_PATH.mkdir(parents=True, exist_ok=True)
        
        dataset_path = self.DATA_PATH / '3dshapes.npz'
        if not dataset_path.exists():
            h5_path = self.DATA_PATH / '3dshapes.h5'
            logging.info('Downloading dataset from %s', ThreeDShapes._H5_URL)
            urllib.request.urlretrieve(ThreeDShapes._H5_URL, str(h5_path))
            logging.info('Dataset stored in %s', dataset_path)
            logging.info('Extracting dataset in %s as npz', self.DATA_PATH)

            try:
                import h5py
            except ImportError as exc:
                raise ImportError(
                    'ThreeDShapes requires h5py. Install h5py to load this dataset.'
                ) from exc

            with h5py.File(h5_path, 'r') as f:
                imgs: np.ndarray = f['images'][:] # type: ignore
                latents_values: np.ndarray = f['labels'][:] # type: ignore
            
            latents_classes = deepcopy(latents_values)
            for k in range(latents_values.shape[1]):
                vals = np.unique(latents_values[:, k])
                val_to_idx = {v: i for i, v in enumerate(vals)}
                latents_classes[:, k] = np.vectorize(val_to_idx.get)(latents_classes[:, k])
            latents_classes = latents_classes.astype(np.int64)

            imgs = imgs / 255.0
            imgs = imgs.astype(np.float32)
            imgs = imgs.transpose(0, 3, 1, 2)
                
            np.savez_compressed(dataset_path, 
                                imgs=imgs, 
                                latents_values=latents_values, 
                                latents_classes=latents_classes, 
            )
            logging.info('Dataset stored in %s', dataset_path)
        
        data = np.load(dataset_path, allow_pickle=True)

        # storing data as tensors
        self.X = torch.as_tensor(data['imgs'], dtype=torch.float32)
        self.latents_classes = torch.as_tensor(data['latents_classes'], dtype=torch.int64)
        self.latents_values = torch.as_tensor(data['latents_values'], dtype=torch.float32)
        
        self.latents_factors = self.latents_classes.shape[1]
        # from https://github.com/google-deepmind/dsprites-dataset/blob/master/dsprites_reloading_example.ipynb, 
        #      same logic: https://github.com/google-deepmind/3d-shapes
        # together with latent_to_index fn
        latents_sizes = np.array([len(self.latents_classes[:, d].unique()) for d in range(self.latents_factors)])
        latents_bases = np.concatenate((latents_sizes[::-1].cumprod()[::-1][1:],
                                np.array([1,])))
        self.latents_sizes = torch.as_tensor(latents_sizes, dtype=torch.int64)
        self.latents_bases = torch.as_tensor(latents_bases, dtype=torch.int64)

        # latent common factors
        self.K = K
        if K != -1: # random
            assert 0 < self.K < self.latents_factors, 'k must be in 0 < k < #latentdims'

    
    def __len__(self) -> int:
        """Return the total number of samples in the dataset."""
        return self.X.shape[0]
    
    def latent_to_index(self, latents: torch.Tensor) -> torch.Tensor:
        """
        Convert latent factor indices to dataset sample index.

        Parameters
        ----------
        latents : torch.Tensor
            Latent factor indices.

        Returns
        -------
        torch.Tensor
            Dataset index corresponding to the latent factors.
        """
        return torch.dot(latents, self.latents_bases)
    
    def __getitem__(self, index):
        """
        Get a sample from the dataset.

        Parameters
        ----------
        index : int
            Index of the sample to retrieve.

        Returns
        -------
        If paired=False:
            tuple of (image, latent_factors)
                image : torch.Tensor
                    Image tensor of shape (1, 64, 64).
                latent_factors : torch.Tensor
                    Discrete latent factor indices.

        If paired=True:
            tuple of ((image1, image2), (factors1, factors2))
                image1, image2 : torch.Tensor
                    Paired images differing in K latent factors.
                factors1, factors2 : torch.Tensor
                    Discrete latent factor indices for each image.
        """
        x1, y1 = self.X[index], self.latents_classes[index]
        if not self.paired:
            return x1, y1
        
        k: int = self.K if self.K != -1 else int(torch.randint(1, int(self.latents_factors), ()))
        
        y2 = y1.clone()
        
        idxs_k = torch.randperm(self.latents_factors)[:k]
        S = self.latents_sizes[idxs_k]
        
        offsets = (torch.rand(k) * (S-1)).long() + 1
        y2[idxs_k] = (y2[idxs_k] + offsets) % S
        x2 = self.X[self.latent_to_index(y2)]

        return (x1, x2), (y1, y2)
